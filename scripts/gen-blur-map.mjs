// Generates src/lib/blurData.ts — a { "/images/...": "data:image/webp;base64,..." } map of tiny
// blur placeholders for every product image under public/images/Jewelries/.
//
// Why: product images are referenced by string path (see src/lib/productImages.ts), so Next.js can't
// auto-generate a blurDataURL the way it does for statically-imported images (e.g. SeasonalBanner).
// This bakes a ~20px base64 preview per image so <Image placeholder="blur"> has something to show
// until the full image loads, then Next swaps in the original.
//
// Re-run after adding/replacing images:  node scripts/gen-blur-map.mjs

import { readdir, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";
import sharp from "sharp";

const ROOT = process.cwd();
const IMAGES_DIR = join(ROOT, "public", "images", "Jewelries");
const OUT_FILE = join(ROOT, "src", "lib", "blurData.ts");

const files = (await readdir(IMAGES_DIR)).filter((f) => /\.(webp|png|jpe?g)$/i.test(f)).sort();

const entries = [];
for (const file of files) {
  const abs = join(IMAGES_DIR, file);
  // 20px wide keeps the data URL tiny (~a few hundred bytes) while still carrying the image's colour
  // layout; Next.js upscales + blurs it, so fine detail is wasted anyway.
  const buf = await sharp(abs).resize(20).webp({ quality: 40 }).toBuffer();
  const dataUrl = `data:image/webp;base64,${buf.toString("base64")}`;
  // Public path is what productImage() returns and what <Image src> receives.
  const publicPath = "/" + relative(join(ROOT, "public"), abs).split("\\").join("/");
  entries.push([publicPath, dataUrl]);
}

const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
const out = `// AUTO-GENERATED by scripts/gen-blur-map.mjs — do not edit by hand.
// Tiny base64 blur placeholders for product images (string-path <Image>s can't auto-generate one).
// Regenerate:  node scripts/gen-blur-map.mjs

export const BLUR_DATA: Record<string, string> = {
${body}
};

// blurDataURL for a product image path, or undefined if we have no preview baked for it.
export function blurFor(src: string): string | undefined {
  return BLUR_DATA[src];
}
`;

await writeFile(OUT_FILE, out, "utf8");
console.log(`Wrote ${entries.length} blur entries → ${relative(ROOT, OUT_FILE)}`);
